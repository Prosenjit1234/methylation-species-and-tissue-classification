print(confusion_matrix(Y_test, y_pred_binary))
print("\nClassification Report:")
print(classification_report(Y_test, y_pred_binary))

# Compute ROC-AUC
roc_auc = roc_auc_score(Y_test, y_pred)
print(f"ROC AUC Score: {roc_auc:.4f}")

