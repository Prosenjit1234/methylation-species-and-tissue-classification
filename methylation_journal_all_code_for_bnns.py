import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import confusion_matrix, classification_report, roc_auc_score
import tensorflow as tf
from imblearn.over_sampling import SMOTE

# Load Dataset
file_path = "/content/HMS VS WED(ch)transposed.csv"
data = pd.read_csv(file_path, low_memory=False)

# Display basic dataset info
print(data.head())
print(data.info())

# Ensure all columns except the target are numeric
# Drop non-numeric columns like 'Position' if necessary
data = data.select_dtypes(include=[np.number])

# Separate features and target
target_column = "Classification"  # Replace with the correct target column
if target_column not in data.columns:
    print("Ensure the target column name matches your dataset.")
    exit()

X = data.drop(columns=[target_column])
Y = data[target_column].astype(int)  # Convert target to integer type

print(f"Class distribution: {np.bincount(Y)}")

# Train-Test Split
X_train, X_test, Y_train, Y_test = train_test_split(X, Y, test_size=0.2, random_state=42, stratify=Y)

# Normalize features
scaler = StandardScaler()
